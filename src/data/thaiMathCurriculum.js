/**
 * Get chapters based on grade, term (1/2), and type (basic/additional)
 * Returns array of Strings for compatibility, but logs full objects for debugging.
 */
export const getChapters = (grade, term, type = 'basic') => {
    // 1. Get Grade Data
    const gradeData = IPST_CURRICULUM[grade];
    if (!gradeData) return [];

    // 2. Get Term Data
    const termKey = (term === '1' || term === 'Term1') ? 'Term1' : 'Term2';
    const termContent = gradeData[termKey];

    if (!termContent) return [];

    let chapters = [];

    // 3. Handle structure
    if (Array.isArray(termContent)) {
        // Lower Secondary (M1-M3)
        chapters = termContent;
    } else {
        // Upper Secondary (M4-M6) — case-insensitive match for 'Additional'/'additional'
        const typeKey = (String(type).toLowerCase() === 'additional') ? 'Additional' : 'Basic';
        chapters = termContent[typeKey] || [];
    }

    // Return only titles for backward compatibility with <select> options
    return chapters.map(c => c.title);
};

// New helper to get full object if needed later
export const getChapterObject = (grade, term, title, type = 'basic') => {
    // Re-use logic to get list, then find
    const gradeData = IPST_CURRICULUM[grade];
    if (!gradeData) return null;
    const termKey = (term === '1' || term === 'Term1') ? 'Term1' : 'Term2';
    const termContent = gradeData[termKey];
    if (!termContent) return null;

    let chapters = [];
    if (Array.isArray(termContent)) {
        chapters = termContent;
    } else {
        const typeKey = (String(type).toLowerCase() === 'additional') ? 'Additional' : 'Basic';
        chapters = termContent[typeKey] || [];
    }

    return chapters.find(c => c.title === title);
}
